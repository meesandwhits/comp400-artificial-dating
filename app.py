@app.route("/verify", methods=["POST"])
def verify_captcha():
    # 1. Grab the token generated by the Turnstile widget
    token = request.form.get("cf-turnstile-response")

    # If the user clicked the button without letting the CAPTCHA run
    if not token:
        return render_template("index.html", error="Please complete the CAPTCHA check before proceeding.")

    # 2. Ask Cloudflare if the token is valid
    verify_url = "https://challenges.cloudflare.com/turnstile/v0/siteverify"
    payload = {
        "secret": CLOUDFLARE_SECRET_KEY,
        "response": token
    }
    
    response = requests.post(verify_url, data=payload)
    result = response.json()

    # 3. Check Cloudflare's verdict
    if result.get("success"):
        # Passed: Forward them to the next page
        return redirect(url_for("start_page"))
    else:
        # Failed: Keep them on index.html with an error message
        return render_template("index.html", error="Verification failed. Please try again.")

